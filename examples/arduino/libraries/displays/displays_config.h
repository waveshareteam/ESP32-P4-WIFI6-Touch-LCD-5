// LCD backlight is driven by GPIO26 on this board, exactly like the audited
// BSP: a 5 kHz / 10-bit LEDC PWM signal (duty 1023 = 100% brightness). The
// panel's backlight path AC-couples the PWM signal, so a static GPIO level
// does not light the LEDs.
#define LCD5_BACKLIGHT_PIN ((int8_t)26)
#define LCD5_BACKLIGHT_FREQ 5000
#define LCD5_BACKLIGHT_RES 10

inline void display_cfg_backlight(bool on) {
  ledcAttach(LCD5_BACKLIGHT_PIN, LCD5_BACKLIGHT_FREQ, LCD5_BACKLIGHT_RES);
  ledcWrite(LCD5_BACKLIGHT_PIN, on ? ((1 << LCD5_BACKLIGHT_RES) - 1) : 0);
}

